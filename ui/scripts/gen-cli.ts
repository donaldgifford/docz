/*
 * Generates the TypeScript types and the consumer's open schemas for the
 * docz CLI's JSON contract (DESIGN-0024 §3) from ../api/cli/*.schema.json.
 *
 * Two outputs per schema, both under src/cli/__generated__/ (gitignored,
 * like the orval client):
 *   <name>.ts         the types, from json-schema-to-typescript
 *   <name>.open.json  the schema with every additionalProperties removed,
 *                     which is what a consumer validates against: the
 *                     producer's closed schema is its drift detector, and
 *                     a consumer must ignore fields it does not know.
 *
 * Run with `bun run gen-cli`; `scripts/gen-cli-check.sh` is the drift gate.
 */
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

import { compile, type JSONSchema } from "json-schema-to-typescript";

const here = fileURLToPath(new URL(".", import.meta.url));
const schemaDir = join(here, "..", "..", "api", "cli");
const outDir = join(here, "..", "src", "cli", "__generated__");

const BANNER =
  "/* Generated by scripts/gen-cli.ts from api/cli. Do not edit. */";

/** openSchema returns a copy with every additionalProperties removed. */
export function openSchema(node: unknown): unknown {
  if (Array.isArray(node)) {
    return node.map(openSchema);
  }
  if (node !== null && typeof node === "object") {
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(node)) {
      if (key === "additionalProperties") {
        continue;
      }
      out[key] = openSchema(value);
    }
    return out;
  }
  return node;
}

async function main(): Promise<void> {
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  const files = (await readdir(schemaDir))
    .filter((f) => f.endsWith(".schema.json"))
    .sort();

  for (const file of files) {
    const name = basename(file, ".schema.json");
    const schema = JSON.parse(
      await readFile(join(schemaDir, file), "utf8"),
    ) as JSONSchema;

    const ts = await compile(schema, `Cli${pascal(name)}`, {
      bannerComment: BANNER,
      additionalProperties: false,
      strictIndexSignatures: true,
      unreachableDefinitions: true,
      format: true,
    });

    await writeFile(join(outDir, `${name}.ts`), ts);
    await writeFile(
      join(outDir, `${name}.open.json`),
      `${JSON.stringify(openSchema(schema), null, 2)}\n`,
    );
  }

  console.log(`gen-cli: wrote ${String(files.length)} schemas to ${outDir}`);
}

function pascal(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

await main();
