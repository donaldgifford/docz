/*
 * Generates review/__generated__/assets.ts from Vite's manifest for the
 * review page (DESIGN-0024 section 10): one `with { type: "file" }`
 * import per emitted file and its MIME type, so `bun build --compile`
 * embeds every chunk, stylesheet, font, and lazy Shiki or Mermaid payload,
 * and the binary serves the page with no dist-review beside it.
 *
 * The manifest is the source of truth for what the page can load; the
 * HTML entries it names are added, since the manifest lists their
 * scripts, not the pages themselves. Run after `vite build --mode review`.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

interface Chunk {
  file: string;
  src?: string;
  isEntry?: boolean;
  css?: string[];
  assets?: string[];
}

// Every kind of file the page build emits. An unknown extension fails the
// build rather than being served as something it is not.
const MIME: Record<string, string> = {
  ".html": "text/html;charset=utf-8",
  ".js": "text/javascript;charset=utf-8",
  ".css": "text/css;charset=utf-8",
  ".json": "application/json;charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".woff2": "font/woff2",
  ".woff": "font/woff",
  ".ttf": "font/ttf",
  ".wasm": "application/wasm",
};

const here = fileURLToPath(new URL(".", import.meta.url));
const dist = join(here, "..", "dist-review");
const outDir = join(here, "..", "review", "__generated__");

const manifest = JSON.parse(
  await readFile(join(dist, ".vite", "manifest.json"), "utf8"),
) as Record<string, Chunk>;

const files = new Set<string>();
for (const [key, chunk] of Object.entries(manifest)) {
  files.add(chunk.file);
  for (const f of [...(chunk.css ?? []), ...(chunk.assets ?? [])]) {
    files.add(f);
  }
  if (chunk.isEntry === true && key.endsWith(".html")) {
    files.add(key);
  }
}
if (![...files].some((f) => f.endsWith(".html"))) {
  throw new Error("the manifest names no HTML entry; was review.html built?");
}

const sorted = [...files].sort();
const lines = [
  "/* Generated by scripts/embed-manifest.ts from dist-review. Do not edit. */",
  'import type { Asset } from "../server";',
  "",
];
const entries: string[] = [];
for (const [i, file] of sorted.entries()) {
  const path = join(dist, file);
  const type = MIME[extname(file)];
  if (type === undefined) {
    throw new Error(`no MIME type for ${file}; add its extension to MIME`);
  }
  const spec = relative(outDir, path);
  lines.push(
    `import f${String(i)} from ${JSON.stringify(spec)} with { type: "file" };`,
  );
  entries.push(
    `  ${JSON.stringify(`/${file}`)}: { file: f${String(i)}, type: ${JSON.stringify(type)} },`,
  );
}
lines.push(
  "",
  "export const ASSETS: Record<string, Asset> = {",
  ...entries,
  "};",
  "",
);

await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, "assets.ts"), lines.join("\n"));
console.log(`embed-manifest: ${String(sorted.length)} assets`);
