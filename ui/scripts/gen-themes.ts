/*
 * Generates src/theme/__generated__/themes.ts (gitignored, like the CLI
 * types) from the token files under ../pkg/theme/tokens/, so the site,
 * its server, and the review page all know the themes pkg/theme has
 * without a hand-kept list (IMPL-0030 open question 5). A theme added
 * to pkg/theme is selectable here after `bun run gen-themes`.
 *
 * Each theme's name is its file's name. A theme has modes when its file
 * carries a `[data-mode="dark"]` block; the others have one look in
 * every mode, so the light/dark toggle hides on them. `paper` is first,
 * as pkg/theme.Names() orders it, and the default; the rest follow by
 * name.
 *
 * Run with `bun run gen-themes`; `scripts/gen-themes-check.sh` is the
 * drift gate.
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const tokensDir = join(here, "..", "..", "pkg", "theme", "tokens");
const outDir = join(here, "..", "src", "theme", "__generated__");

const DEFAULT_THEME = "paper";
const DARK_BLOCK = /\[data-mode="dark"\]/;

interface ThemeInfo {
  name: string;
  modes: boolean;
}

async function themes(): Promise<ThemeInfo[]> {
  const files = (await readdir(tokensDir)).filter((f) => f.endsWith(".css"));
  const found = await Promise.all(
    files.map(async (file) => ({
      name: basename(file, ".css"),
      modes: DARK_BLOCK.test(await readFile(join(tokensDir, file), "utf8")),
    })),
  );
  if (!found.some((t) => t.name === DEFAULT_THEME)) {
    throw new Error(`gen-themes: ${tokensDir} has no ${DEFAULT_THEME}.css`);
  }
  return found.sort((a, b) =>
    a.name === DEFAULT_THEME
      ? -1
      : b.name === DEFAULT_THEME
        ? 1
        : a.name.localeCompare(b.name),
  );
}

function source(list: ThemeInfo[]): string {
  const names = list.map((t) => JSON.stringify(t.name)).join(", ");
  const withModes = list
    .filter((t) => t.modes)
    .map((t) => JSON.stringify(t.name))
    .join(", ");
  return `/* Generated by scripts/gen-themes.ts from pkg/theme/tokens. Do not edit. */

/** Every theme pkg/theme has, the default first. */
export const THEMES = [${names}] as const;

export type ThemeName = (typeof THEMES)[number];

/** The theme a surface shows when nothing names one. */
export const DEFAULT_THEME: ThemeName = ${JSON.stringify(DEFAULT_THEME)};

/** The themes with a light and a dark look. */
export const THEMES_WITH_MODES: readonly ThemeName[] = [${withModes}];
`;
}

await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, "themes.ts"), source(await themes()));
